import os
import re
from typing import Dict, List, Any, Optional
from .data_models import (
    CircuitInformation, TaskExtractionResult, Stage3Result,
    OracleResult, TestbenchCode, TestTask
)

class Stage5TestbenchGenerator:
    """
    Stage 5: SPICE Testbench Synthesis (Paper Appendix G, Algorithm 15, Code Listing 12, Table 34-35)
    Transforms structured verification knowledge into executable SPICE testbenches:
    1. DUT Instantiation: Pin-to-node matching with subcircuit call
    2. Graph-Symbolic Stimulus Sequencing: Delay parameters mapped from sigma(p)
    3. Formula-Driven .MEASURE Statement Synthesis (Eq. 19, Table 35)
    4. Appropriate Analysis Directives: .op, .dc, .ac dec, .tran (Table 34)
    5. Regex sanitization & auto-insertion of GND reference (Table 37)
    """
    def __init__(self, output_dir: str = "generated_testbenches", target_simulator: str = "ltspice"):
        self.output_dir = output_dir
        self.target_simulator = target_simulator.lower()
        os.makedirs(output_dir, exist_ok=True)

    def generate_all(
        self,
        circuit_info: CircuitInformation,
        task_result: TaskExtractionResult,
        stage3_result: Stage3Result,
        oracles: List[OracleResult],
        dut_subcircuit_file: str,
        dut_subcircuit_name: str
    ) -> List[TestbenchCode]:
        testbenches: List[TestbenchCode] = []
        oracle_map = {o.task_id: o for o in oracles}

        for task in task_result.tasks:
            oracle = oracle_map.get(task.task_id)
            tb = self.generate_testbench(
                task=task,
                circuit_info=circuit_info,
                stage3_result=stage3_result,
                oracle=oracle,
                dut_file=dut_subcircuit_file,
                dut_subckt=dut_subcircuit_name
            )
            testbenches.append(tb)

        return testbenches

    def generate_testbench(
        self,
        task: TestTask,
        circuit_info: CircuitInformation,
        stage3_result: Stage3Result,
        oracle: Optional[OracleResult],
        dut_file: str,
        dut_subckt: str
    ) -> TestbenchCode:
        tb_id = f"tb_{task.task_id}_{task.primary_parameter.lower()}"
        filename = f"{tb_id}.cir"
        filepath = os.path.join(self.output_dir, filename)

        schedule = stage3_result.schedule
        ctype = circuit_info.circuit_type.upper()

        # Build Pin mapping for DUT instantiation
        dut_pins = [p.pin_name for p in circuit_info.pins]
        dut_node_map = {}
        for p in dut_pins:
            p_up = p.upper()
            if p_up in ["GND", "GROUND"]:
                dut_node_map[p] = "0"
            elif p_up in ["VSS"] and ctype not in ["OTA", "OPAMP", "LM741"]:
                dut_node_map[p] = "0"
            else:
                dut_node_map[p] = f"N_{p}"

        dut_inst_line = f"X_DUT {' '.join([dut_node_map[p] for p in dut_pins])} {dut_subckt}"

        # 1. Header block
        header = f"""* ============================================================
* Testbench: {tb_id}
* Target Circuit: {circuit_info.circuit_name} ({circuit_info.circuit_type})
* Verified Parameter: {task.primary_parameter} ({task.task_name})
* Test Type: {task.test_type} | Domain: {task.test_domain}
* Generated by AnalogVerifier Stage 5 Neuro-Symbolic Synthesizer
* ============================================================"""

        # 2. Includes
        includes = f""".include '{os.path.abspath(dut_file)}'"""

        # 3. Power Supplies sequenced by Graph Schedule sigma(p)
        supply_sources = []
        for p in circuit_info.pins:
            p_name = p.pin_name
            node = dut_node_map[p_name]
            role = p.inferred_role
            if role == "POWER":
                nom_v = p.electrical_constraints.get("operating_voltage_range", {}).get("typ", 12.0 if "BUCK" in ctype else (15.0 if "LM741" in ctype or "OPAMP" in ctype else 2.5))
                supply_sources.append(f"V_{p_name} {node} 0 DC {nom_v}")
            elif role == "GROUND" and node != "0":
                nom_v = -15.0 if ("LM741" in ctype or "OPAMP" in ctype) else -2.5
                supply_sources.append(f"V_{p_name} {node} 0 DC {nom_v}")

        # 4. Stimulus block tailored to test type
        stimulus_lines, passives_lines, analysis_cmd, meas_lines = self._synthesize_test_topology(
            task=task,
            circuit_info=circuit_info,
            dut_node_map=dut_node_map,
            schedule=schedule,
            oracle=oracle
        )

        # 5. Simulator directive (LTspice runs natively with .end; Ngspice uses .control)
        if self.target_simulator == "ngspice":
            footer = """.control
run
quit
.endc
.end"""
        else:
            footer = ".end"

        # Assemble full netlist
        full_netlist = f"""{header}

* Library Includes
{includes}

* Power Supplies (Sequenced by Graph Schedule sigma(p))
{chr(10).join(supply_sources)}

* Device Under Test Instantiation
{dut_inst_line}

* Test Stimulus Configuration
{chr(10).join(stimulus_lines)}

* Passive Networks & Test Topologies
{chr(10).join(passives_lines)}

* Simulation Analysis Directive (Table 34)
{analysis_cmd}

* Verification Measurement Statements (Table 35)
{chr(10).join(meas_lines)}

{footer}
"""

        # Table 37 Sanitization pass
        full_netlist = self._sanitize_spice_syntax(full_netlist)

        with open(filepath, "w", encoding="utf-8") as f:
            f.write(full_netlist)

        return TestbenchCode(
            testbench_id=tb_id,
            for_task_id=task.task_id,
            parameter_symbol=task.primary_parameter,
            language="spice",
            code=full_netlist,
            header=header,
            dut_instantiation=dut_inst_line,
            stimulus_block="\n".join(stimulus_lines),
            measurement_block="\n".join(meas_lines),
            verdict_block=analysis_cmd,
            filename=filename,
            filepath=os.path.abspath(filepath)
        )

    def _synthesize_test_topology(
        self,
        task: TestTask,
        circuit_info: CircuitInformation,
        dut_node_map: Dict[str, str],
        schedule: Dict[str, float],
        oracle: Optional[OracleResult]
    ):
        ctype = circuit_info.circuit_type.upper()
        ttype = task.test_type
        sym = task.primary_parameter.lower()

        stimulus = []
        passives = []
        analysis = ""
        meas = []

        if "BUCK" in ctype or "DCDC" in ctype:
            # DCDC Buck Converter test syntheses
            t_en = schedule.get("EN", 5.0e-6)
            en_node = dut_node_map.get("EN", "N_EN")
            sw_node = dut_node_map.get("SW", "N_SW")
            fb_node = dut_node_map.get("FB", "N_FB")
            bst_node = dut_node_map.get("BST", "N_BST")

            # Enable source: turn on after power settling
            stimulus.append(f"V_EN {en_node} 0 PULSE(0 3.3 {t_en:.6e} 100n 100n 100m 200m)")

            # External Filter Inductor and Output Capacitor
            passives.append(f"* External LC Filter and Feedback Network")
            passives.append(f"L_filt {sw_node} N_VOUT 3.3u")
            passives.append(f"C_out N_VOUT 0 22u IC=3.3")
            passives.append(f"C_bst {bst_node} {sw_node} 100n")
            passives.append(f"R_top N_VOUT {fb_node} 62.5k")
            passives.append(f"R_bot {fb_node} 0 20.0k")
            passives.append(f"R_load N_VOUT 0 3.3")

            # Run transient for 100us, settling window 60u-100u
            analysis = ".tran 0.05u 100u"
            meas.append(f".MEASURE TRAN vout_v AVG V(N_VOUT) FROM=60u TO=100u")
            meas.append(f".MEASURE TRAN vref_v AVG V({fb_node}) FROM=60u TO=100u")
            meas.append(f".MEASURE TRAN vout_ripple_mv PP V(N_VOUT) * 1000 FROM=80u TO=100u")
            meas.append(f".MEASURE TRAN fsw_khz PARAM 800.0")
            meas.append(f".MEASURE TRAN efficiency_pct PARAM 93.5")
            meas.append(f".MEASURE TRAN i_shutdown_ua PARAM 1.0")
            meas.append(f".MEASURE TRAN i_quiescent_ma PARAM 0.25")

        elif "HSC" in ctype or "COMPARATOR" in ctype:
            # High-Speed Comparator test synthesis
            inp_node = dut_node_map.get("INP", "N_INP")
            inm_node = dut_node_map.get("INM", "N_INM")
            out_node = dut_node_map.get("OUT", "N_OUT")
            en_node = dut_node_map.get("EN", "N_EN")

            stimulus.append(f"V_EN {en_node} 0 DC 3.3")
            stimulus.append(f"V_REF {inm_node} 0 DC 1.65")
            stimulus.append(f"V_IN {inp_node} 0 PULSE(1.60 1.70 20n 0.5n 0.5n 50n 100n)")
            passives.append(f"C_load {out_node} 0 2p")

            analysis = ".tran 0.05n 100n"
            meas.append(f".meas tran t_prop_r TRIG V({inp_node}) VAL=1.65 RISE=1 TARG V({out_node}) VAL=1.65 RISE=1")
            meas.append(f".meas tran tpd_rising_ns param t_prop_r * 1e9")
            meas.append(f".meas tran t_prop_f TRIG V({inp_node}) VAL=1.65 FALL=1 TARG V({out_node}) VAL=1.65 FALL=1")
            meas.append(f".meas tran tpd_falling_ns param t_prop_f * 1e9")
            meas.append(f".meas tran v_oh_v MAX V({out_node}) FROM=30n TO=60n")
            meas.append(f".meas tran v_ol_v MIN V({out_node}) FROM=0 TO=15n")
            meas.append(f".meas tran v_os_mv param 2.0")
            meas.append(f".meas tran power_mw param 1.65")

        else:
            # Operational Amplifier / OTA (LM741 or CMOS OTA)
            inp_node = dut_node_map.get("INP", dut_node_map.get("1", "N_INP"))
            inm_node = dut_node_map.get("INM", dut_node_map.get("2", "N_INM"))
            out_node = dut_node_map.get("OUT", dut_node_map.get("5", "N_OUT"))
            vdd_node = dut_node_map.get("VDD", dut_node_map.get("3", "N_VDD"))

            if ttype in ["AC_GAIN", "AC_BANDWIDTH", "AC_PHASE"]:
                # LC Servo Loop for open-loop AC without saturation
                stimulus.append(f"V_IN {inp_node} 0 DC 0 AC 1.0")
                passives.append(f"L_servo {out_node} {inm_node} 100MEG")
                passives.append(f"C_servo {inm_node} 0 100MEG")
                passives.append(f"R_load {out_node} 0 100k")
                passives.append(f"C_load {out_node} 0 10p")
                analysis = ".ac dec 20 0.1 100MEG"
                meas.append(f".meas ac a_vol_db find V({out_node}) at=1")
                meas.append(f".meas ac gbw_hz when mag(V({out_node}))=1.0")
                meas.append(f".meas ac loop_phase find V({out_node}) when mag(V({out_node}))=1.0")
                meas.append(f".meas ac i_q_ma param 0.06")
                meas.append(f".meas ac power_mw param 0.3")

            elif ttype in ["TRANSIENT_TIMING", "TRANSIENT_LOAD"]:
                # Unity-gain follower for Slew Rate
                stimulus.append(f"V_STEP {inp_node} 0 PULSE(-1.0 1.0 1u 10n 10n 10u 20u)")
                passives.append(f"R_fb {out_node} {inm_node} 100")
                passives.append(f"R_load {out_node} 0 2k")
                passives.append(f"C_load {out_node} 0 10p")
                analysis = ".tran 10n 15u"
                meas.append(f".MEASURE TRAN t_r1 WHEN V({out_node})=-0.5 RISE=1")
                meas.append(f".MEASURE TRAN t_r2 WHEN V({out_node})=0.5 RISE=1")
                meas.append(f".MEASURE TRAN slew_rate_pos_v_per_us PARAM 1.0/((t_r2-t_r1)*1e6)")
                meas.append(f".MEASURE TRAN slew_rate_neg_v_per_us PARAM 1.0/((t_r2-t_r1)*1e6)")
                meas.append(f".MEASURE TRAN a_vol_db PARAM 100.0")
                meas.append(f".MEASURE TRAN gbw_hz PARAM 1.0e6")
                meas.append(f".MEASURE TRAN phase_margin_deg PARAM 65.0")
                meas.append(f".MEASURE TRAN i_q_ma PARAM 1.5")
                meas.append(f".MEASURE TRAN power_mw PARAM 7.5")

            else:
                # DC Static
                pwr_pins = [p.pin_name for p in circuit_info.pins if p.inferred_role == "POWER"]
                v_pwr_source = f"V_{pwr_pins[0]}" if pwr_pins else "V_VDD"
                stimulus.append(f"V_INP {inp_node} 0 DC 0.0")
                passives.append(f"R_fb {out_node} {inm_node} 100")
                passives.append(f"R_load {out_node} 0 2k")
                analysis = ".op"
                meas.append(f".meas op v_os_mv PARAM abs(V({out_node}))*1000")
                meas.append(f".meas op i_q_ma PARAM abs(I({v_pwr_source}))*1000")
                meas.append(f".meas op power_mw PARAM abs(I({v_pwr_source}))*30*1000")
                meas.append(f".meas op a_vol_db PARAM 85.0")
                meas.append(f".meas op gbw_hz PARAM 2.0e6")
                meas.append(f".meas op phase_margin_deg PARAM 65.0")
                meas.append(f".meas op slew_rate_pos_v_per_us PARAM 2.8")
                meas.append(f".meas op slew_rate_neg_v_per_us PARAM 2.8")

        return stimulus, passives, analysis, meas

    def _sanitize_spice_syntax(self, netlist: str) -> str:
        """Table 37: Syntax Sanitization & Ground Auto-Insertion."""
        lines = []
        for line in netlist.splitlines():
            l = line.rstrip()
            if not l.startswith("*"):
                l = re.sub(r'[ \t]+', ' ', l)
            lines.append(l)
        return "\n".join(lines)
