import math
import os

class ParametricSynthesizer:
    def __init__(self, target_specs):
        self.specs = target_specs

    def synthesize_initial_parameters(self):
        """Computes physical and behavioral component values from datasheet targets."""
        # Target specs
        gbw_target = self.specs["GBW_Hz"]["typ"]
        avol_db = self.specs["A_vol_dB"]["typ"]
        avol_linear = 10.0 ** (avol_db / 20.0)
        pm_target = self.specs["Phase_Margin_deg"]["typ"]
        sr_target = self.specs["Slew_Rate_pos_V_per_us"]["typ"] * 1e6 # V/s
        vos = self.specs["V_os_mV"]["typ"] * 1e-3
        ib = self.specs["I_b_nA"]["typ"] * 1e-9
        ios = self.specs["I_os_nA"]["typ"] * 1e-9
        iq = self.specs["I_q_mA"]["typ"] * 1e-3
        cmrr_db = self.specs["CMRR_dB"]["typ"]
        psrr_db = self.specs["PSRR_pos_dB"]["typ"]
        vom_pos = self.specs["V_om_pos_V"]["typ"]

        # Component sizing
        cc = 30e-12 # 30pF standard LM741 compensation capacitor
        gm1 = 2.0 * math.pi * gbw_target * cc
        i_tail = sr_target * cc
        ro1 = avol_linear / gm1

        # Phase margin: second pole fp2
        # phase lag = 90 + arctan(gbw / fp2) = 180 - pm => arctan(gbw / fp2) = 90 - pm
        phi_deg = 90.0 - pm_target
        if phi_deg <= 0:
            phi_deg = 1.0
        fp2 = gbw_target / math.tan(math.radians(phi_deg))
        rp2 = 10e3
        cp2 = 1.0 / (2.0 * math.pi * rp2 * fp2)

        cmrr_att = 10.0 ** (-cmrr_db / 20.0)
        psrr_att = 10.0 ** (-psrr_db / 20.0)

        v_supply = 15.0
        vdrop_pos = max(0.5, v_supply - vom_pos)
        vdrop_neg = vdrop_pos

        params = {
            "Vos": vos,
            "Ib": ib,
            "Ios": ios,
            "Rin": 2e6,
            "Rcm": 500e6,
            "Cc": cc,
            "Gm1": gm1,
            "I_tail": i_tail,
            "Ro_stage1": ro1,
            "Rp2": rp2,
            "Cp2": cp2,
            "Rout": 75.0,
            "Iq": iq,
            "Cmrr_att": cmrr_att,
            "Psrr_att": psrr_att,
            "Vdrop_pos": vdrop_pos,
            "Vdrop_neg": vdrop_neg
        }
        return params

    def generate_subcircuit(self, params, output_path):
        """Generates a SPICE subcircuit (.sub) with the given parameters."""
        content = f"""* Automated Synthesized Parametric SPICE Macromodel for OpAmp (TI LM741 Architecture)
* Generated by Analog Circuit Design AI Agent
* Terminal Pins: IN+ IN- VCC VEE OUT
.subckt LM741_MACRO 1 2 3 4 5
* 1: IN+ (non-inverting)
* 2: IN- (inverting)
* 3: VCC (+15V typ)
* 4: VEE (-15V typ)
* 5: OUT

.param Vos = {params['Vos']:.6e}
.param Ib = {params['Ib']:.6e}
.param Ios = {params['Ios']:.6e}
.param Rin = {params['Rin']:.6e}
.param Rcm = {params['Rcm']:.6e}
.param Cc = {params['Cc']:.6e}
.param Gm1 = {params['Gm1']:.6e}
.param I_tail = {params['I_tail']:.6e}
.param Ro_stage1 = {params['Ro_stage1']:.6e}
.param Rp2 = {params['Rp2']:.6e}
.param Cp2 = {params['Cp2']:.6e}
.param Rout = {params['Rout']:.6e}
.param Iq = {params['Iq']:.6e}
.param Cmrr_att = {params['Cmrr_att']:.6e}
.param Psrr_att = {params['Psrr_att']:.6e}
.param Vdrop_pos = {params['Vdrop_pos']:.6f}
.param Vdrop_neg = {params['Vdrop_neg']:.6f}

* 1. Input Stage: Offset Voltage and Bias Currents
Vos_src 1 11 DC {{Vos}}
R_in_diff 11 2 {{Rin}}
R_in_cm1 11 0 {{Rcm}}
R_in_cm2 2 0 {{Rcm}}
I_b_p 11 0 DC {{Ib + Ios/2}}
I_b_m 2 0 DC {{Ib - Ios/2}}

* 2. Quiescent Supply Current
G_iq 3 4 VALUE = {{Iq}}

* 3. CMRR and PSRR error voltage generation
E_cm_sense 20 0 VALUE = {{(V(11) + V(2)) * 0.5 * Cmrr_att}}
E_psrr_p 21 0 VALUE = {{(V(3) - 15.0) * Psrr_att}}
E_psrr_m 22 0 VALUE = {{(V(4) - (-15.0)) * Psrr_att}}

* 4. Transconductance Stage with Slew-Rate Limiting Current Clamp
B_gm1 0 30 I = LIMIT(Gm1 * (V(11) - V(2) + V(20) + V(21) + V(22)), -I_tail, I_tail)

* Stage 1 Impedance: sets DC Gain and Dominant Pole
R_stage1 30 0 {{Ro_stage1}}
C_stage1 30 0 {{Cc}}

* 5. Second Pole Stage (Sets Phase Margin)
E_buf1 40 0 30 0 1.0
R_pole2 40 41 {{Rp2}}
C_pole2 41 0 {{Cp2}}

* 6. Output Buffer and Rail Clamping Stage
E_out_ideal 50 0 41 0 1.0
B_clamped 60 0 V = MIN(MAX(V(50), V(4) + Vdrop_neg), V(3) - Vdrop_pos)
R_out 60 5 {{Rout}}

.ends LM741_MACRO
"""
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(content)
        return output_path
